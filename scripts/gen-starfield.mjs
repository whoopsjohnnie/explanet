#!/usr/bin/env node
/**
 * gen-starfield.mjs — the real-sky star catalog.
 *
 * Reads the vendored Yale Bright Star Catalog v5 JSON (public domain;
 * scripts/stars/data/BSC.json — all 9,096 naked-eye stars ≤ ~6.5 mag with
 * J2000 positions and spectral class) and emits a compact packed module
 * the app can import: per star, RA and Dec in thousandths of a degree,
 * magnitude in hundredths, and the spectral class OBAFGKM index (7 = unknown;
 * the class string may carry luminosity/variable prefixes, so we take the
 * first OBAFGKM letter). core/starsky.js decodes and projects it.
 *
 * Positions stay in the catalog's own J2000 equatorial frame — the projection
 * into the engine's ecliptic frame happens at load time in starsky.js, so
 * this file is a pure data dump, not a baked sky.
 *
 *   node scripts/gen-starfield.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const IN = join(here, 'stars/data/BSC.json')
const OUT = join(here, '../src/core/starCatalog.js')

const SPECTRAL = { O: 0, B: 1, A: 2, F: 3, G: 4, K: 5, M: 6 }

const parseRA = (s) => {
  const [h, m, sec] = s.split(':').map(Number)
  return (h + m / 60 + sec / 3600) * 15
}
const parseDec = (s) => {
  const sign = s.trimStart().startsWith('-') ? -1 : 1
  const [d, m, sec] = s.replace('+', '').split(':').map(Number)
  return sign * (Math.abs(d) + m / 60 + sec / 3600)
}

const raw = JSON.parse(readFileSync(IN, 'utf8'))
const rows = []
for (const s of raw) {
  const ra = parseRA(s.RA)
  const dec = parseDec(s.DEC)
  const mag = parseFloat(s.MAG)
  if (!Number.isFinite(ra) || !Number.isFinite(dec) || !Number.isFinite(mag)) continue
  if (ra < 0 || ra >= 360 || dec < -90 || dec > 90 || mag < -3 || mag > 8) continue
  const spec = SPECTRAL[((s['Title HD'] || '').match(/[OBAFGKM]/) || [null])[0]] ?? 7
  rows.push([Math.round(ra * 1000), Math.round(dec * 1000), Math.round(mag * 100), spec])
}

const packed = new Int32Array(rows.flat())
const b64 = Buffer.from(packed.buffer).toString('base64')

writeFileSync(
  OUT,
  `/**
 * starCatalog.js — GENERATED by scripts/gen-starfield.mjs, do not edit.
 *
 * Yale Bright Star Catalog v5 (public domain), vendored JSON at
 * scripts/stars/data/BSC.json. ${rows.length} stars, packed Int32Array as
 * base64: 4 ints per star — RA·1000, Dec·1000 (deg, J2000), V·100, spectral
 * class index (OBAFGKM = 0..6, 7 = unknown). Decode + project with
 * core/starsky.js.
 */
export const STAR_B64 =
  '${b64}'
`
)

console.log(`wrote ${OUT}: ${rows.length} stars, ${b64.length} chars base64`)
